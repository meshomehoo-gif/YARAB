/** 12-hour display time with Arabic AM/PM. Digits stay ASCII on purpose. */
fun fmt(h: Int, m: Int): String {
    val hh = if (h % 12 == 0) 12 else h % 12
    return "$hh:${m.toString().padStart(2, '0')} ${if (h >= 12) "م" else "ص"}"
}

/** Parses "HH:mm" (extra text after the first 5 characters is ignored). */
fun parseHm(s: String?): Pair<Int, Int>? {
    if (s == null || s.length < 5) return null
    val p = s.take(5).split(":")
    if (p.size != 2) return null
    val h = p[0].toIntOrNull() ?: return null
    val m = p[1].toIntOrNull() ?: return null
    return Pair(h, m)
}
